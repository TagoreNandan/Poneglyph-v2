@app.post("/api/research")
def run_research(req: ResearchRequest):
    try:
        result = graph.invoke({"query": req.query})
        return {
            "formatted_report": result.get("formatted_report", ""),
            "insights": result.get("insights", {}),
            "sources": result.get("sources", []),
            "route": result.get("route", "Unknown")
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/research/continue")
def continue_research(req: ContinueResearchRequest):
    enhanced_query = f"Original Report:\n\n{req.original_report[:3000]}\n\nFurther Research Request:\n\n{req.deeper_query}"
    try:
        result = graph.invoke({"query": enhanced_query})
        return {
            "formatted_report": result.get("formatted_report", ""),
            "insights": result.get("insights", {}),
            "sources": result.get("sources", []),
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.get("/api/history")
def get_research_history():
    history = get_history()
    # history is a list of tuples: (id, query_text, ...) based on ui/app.py logic
    formatted_history = []
    for item in history:
        formatted_history.append({
            "id": item[0],
            "title": item[1]
        })
    return formatted_history

@app.get("/api/report/{report_id}")
def get_report(report_id: int):
    report = get_report_by_id(report_id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    return {
        "id": report[0],
        "title": report[1],
        "content": report[3]
    }

@app.post("/api/chat")
def handle_chat(req: ChatRequest):
    try:
        answer = chat_with_report(req.report, req.question, req.history)
        return {"answer": answer}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/pdf")
def generate_pdf_endpoint(req: PDFRequest):
    try:
        buffer = generate_pdf(req.report, req.insights)
        return StreamingResponse(
            buffer, 
            media_type="application/pdf",
            headers={"Content-Disposition": "attachment; filename=research_report.pdf"}
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
